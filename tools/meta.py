#!/usr/bin/env python3
"""Top-team draft and build meta from scouted games (Phase 2 item 11, backlog B12; stdlib only).

    python3 tools/meta.py > docs/research/top-team-meta.md

Reads data/scout/<time>.json (the latest tally: drafts and results for the top 20 teams) and
data/scout/summaries/*.json.gz (full summaries: every buyItem event with its round). Writes Markdown:
- how often each champion is drafted, overall and by team size, and the win rate when drafted;
- per champion, the order in which emblem families are completed (from itemCombination events) and the round
  of the first emblem;
- per champion, the share of shards bought per family and stat.
"""
import collections
import glob
import json
import statistics
from pathlib import Path

import features

ROOT = Path(__file__).resolve().parent.parent


def main():
    tally = json.loads(Path(sorted(glob.glob(str(ROOT / "data/scout/2*.json")))[-1]).read_text())
    top_ids = {}
    games = [g | {"team": e["name"]} for e in tally for g in e["games"]]
    for e in tally:
        for g in e["games"]:
            top_ids.setdefault(g["match"], set()).add(g["side"])

    print("# Top-team meta (generated by `tools/meta.py`)\n")
    print(f"Source: the latest `tools/scout.py` tally ({len(tally)} teams, {len(games)} ranked games) and "
          f"{len(glob.glob(str(ROOT / 'data/scout/summaries/*.json.gz')))} full summaries. Regenerate with "
          "`python3 tools/meta.py > docs/research/top-team-meta.md`.\n")

    print("## Draft\n")
    by_size = collections.defaultdict(collections.Counter)
    sizes = collections.Counter()
    picked, wins = collections.Counter(), collections.Counter()
    for g in games:
        n = len(g["picks"])
        sizes[n] += 1
        by_size[n].update(set(g["picks"]))
        picked.update(set(g["picks"]))
        wins.update({p: g["win"] for p in set(g["picks"])})
    cols = sorted(sizes)
    print("| Champion | Drafted | Win % when drafted | " + " | ".join(f"{n} picks (n={sizes[n]})" for n in cols) + " |")
    print("|---|---|---|" + "---|" * len(cols))
    for c, n in picked.most_common():
        print(f"| {c} | {100 * n / len(games):.0f}% | {100 * wins[c] / n:.0f}% | "
              + " | ".join(f"{100 * by_size[s][c] / sizes[s]:.0f}%" for s in cols) + " |")

    order = collections.defaultdict(collections.Counter)
    first_round = collections.defaultdict(list)
    shards = collections.defaultdict(collections.Counter)
    seen = collections.Counter()
    for path in glob.glob(str(ROOT / "data/scout/summaries/*.json.gz")):
        mid = Path(path).name.split(".")[0]
        sides = top_ids.get(mid)
        if not sides:
            continue
        s = features.load(path)
        for e in s.get("events", []):
            team = e["owner"].get("team")
            if team is None or team[-1].lower() not in sides:
                continue
            name = e["owner"].get("name", "?")
            if e["kind"] == "itemCombination" and e["entries"]:
                fams = []
                for entry in sorted(e["entries"], key=lambda x: x["timestamp"]["round"]):
                    fam = entry["target"]["name"].split()[0]
                    if fam not in fams:
                        fams.append(fam)
                order[name][" > ".join(fams[:3])] += 1
                first_round[name].append(min(x["timestamp"]["round"] for x in e["entries"]))
            elif e["kind"] == "buyItem":
                seen[name] += 1
                for entry in e["entries"]:
                    item = entry["target"].get("name", "")
                    if " Shard of " in item:
                        fam, stat = item.split(" Shard of ")
                        shards[name][f"{fam}:{stat}"] += int(entry["value"])

    print("\n## Build order: first three emblem families completed\n")
    print("| Champion | Games | Most common order (share) | 2nd most common | First emblem, median round |")
    print("|---|---|---|---|---|")
    for name in sorted(order, key=lambda n: -sum(order[n].values())):
        total = sum(order[name].values())
        top = order[name].most_common(2)
        second = f"{top[1][0]} ({100 * top[1][1] / total:.0f}%)" if len(top) > 1 else ""
        print(f"| {name} | {total} | {top[0][0]} ({100 * top[0][1] / total:.0f}%) | {second} | "
              f"{statistics.median(first_round[name]):.0f} |")

    print("\n## Shards bought, share by family and stat\n")
    print("| Champion | Games | Top shard types (share of all shards bought) |")
    print("|---|---|---|")
    for name in sorted(shards, key=lambda n: -seen[n]):
        total = sum(shards[name].values()) or 1
        print(f"| {name} | {seen[name]} | " + ", ".join(f"{k} {100 * v / total:.0f}%" for k, v in shards[name].most_common(5)) + " |")


if __name__ == "__main__":
    main()
